static const FVFBGlyph *fvfBFindGlyph(uint32_t cp)
{
  for (uint16_t i = 0; i < FVFB_FONT_COUNT; i++) {
    if (FVFB_FONT[i].cp == cp) return &FVFB_FONT[i];
  }
  return &FVFB_FONT[0];   // khong tim thay -> khoang trang
}

// Giai ma 1 ky tu UTF-8 tai vi tri p, tra ve codepoint va tu dong day p toi
// ky tu tiep theo.
static uint32_t fvfBUtf8Decode(const char *&p)
{
  uint8_t c = (uint8_t)*p++;
  if (c < 0x80) return c;
  if ((c & 0xE0) == 0xC0) {
    uint32_t cp = c & 0x1F;
    cp = (cp << 6) | (uint8_t)(*p++ & 0x3F);
    return cp;
  }
  if ((c & 0xF0) == 0xE0) {
    uint32_t cp = c & 0x0F;
    cp = (cp << 6) | (uint8_t)(*p++ & 0x3F);
    cp = (cp << 6) | (uint8_t)(*p++ & 0x3F);
    return cp;
  }
  if ((c & 0xF8) == 0xF0) {
    uint32_t cp = c & 0x07;
    cp = (cp << 6) | (uint8_t)(*p++ & 0x3F);
    cp = (cp << 6) | (uint8_t)(*p++ & 0x3F);
    cp = (cp << 6) | (uint8_t)(*p++ & 0x3F);
    return cp;
  }
  return c;
}

// Ve 1 ky tu (theo Unicode codepoint) bang font FVF Fernando dam (faux-bold). u8g2 phai
// duoc setDrawColor() truoc. y la dinh khung dong chung (KHONG phai dinh
// ky tu) - glyph tu ve lui xuong dung yOffset da luu san.
static void fvfBDrawChar(U8G2 &u8g2, int x, int y, uint32_t cp)
{
  const FVFBGlyph *g = fvfBFindGlyph(cp);
  for (int row = 0; row < g->height; row++) {
    uint16_t bits = FVFB_ROWDATA[g->dataIndex + row];
    for (int col = 0; col < g->width; col++) {
      if (bits & (0x8000 >> col))
        u8g2.drawPixel(x + col, y + g->yOffset + row);
    }
  }
}

// Ve chuoi UTF-8 (co the co dau tieng Viet) bang font FVF Fernando dam (faux-bold), tra
// ve tong be rong da ve.
static int fvfBDrawString(U8G2 &u8g2, int x, int y, const char *utf8)
{
  int cx = x;
  const char *p = utf8;
  while (*p) {
    uint32_t cp = fvfBUtf8Decode(p);
    const FVFBGlyph *g = fvfBFindGlyph(cp);
    fvfBDrawChar(u8g2, cx, y, cp);
    cx += g->width + 1;
  }
  return cx - x;
}

